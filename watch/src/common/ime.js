/** 带回溯的切分，返回音节数组或 null */
function segment(buf) {
  const memo = {}
  function go(i) {
    if (i >= buf.length) return []
    if (memo[i] !== undefined) return memo[i]
    const max = Math.min(6, buf.length - i)
    for (let k = max; k >= 1; k--) {
      const s = buf.substr(i, k)
      if (STD[s]) {
        const rest = go(i + k)
        if (rest) { memo[i] = [s].concat(rest); return memo[i] }
      }
    }
    memo[i] = null
    return null
  }
  return go(0)
}

/** 取第一个可切分音节（用于候选字），返回 { syl, len } */
export function firstSyl(buf) {
  if (!buf) return null
  const seg = segment(buf)
  if (seg && seg.length) return { syl: seg[0], len: seg[0].length }
  const max = Math.min(6, buf.length)
  for (let k = max; k >= 1; k--) {
    const s = buf.substr(0, k)
    if (STD[s]) return { syl: s, len: k }
  }
  return null
}

/** 候选：整串常用词优先，其次首音节高频字 */
export function candidates(buf) {
  const out = []
  if (!buf) return out
  const words = PH[buf]
  if (words) for (let i = 0; i < words.length; i++) out.push({ t: words[i], n: buf.length })
  const s = firstSyl(buf)
  if (s) {
    const chars = CH[s.syl] || ''
    for (let i = 0; i < chars.length && i < 20; i++) out.push({ t: chars.charAt(i), n: s.len })
  }
  return out
}

export function hasSyl(s) { return !!STD[s] }
