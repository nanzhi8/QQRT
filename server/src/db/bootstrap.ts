/**
 * 建表兜底：无论托管启动脚本是否成功执行了 init.sql，应用自己保证表存在。
 *
 * 背景：PGlite 数据目录在托管沙箱重建后，如果 start.mjs 的建表环节失败，
 * 登录会直接报 `Failed query: select ... from "users"`（表不存在）。
 * 这里用 IF NOT EXISTS 做幂等建表，通过 globalThis 缓存 Promise，
 * 避免 Next.js 每个路由 bundle 重复执行。
 */
import { client } from "./index";

const DDL = `
CREATE TABLE IF NOT EXISTS "contacts" (
  "user_id" text NOT NULL, "kind" text NOT NULL, "openid" text NOT NULL,
  "name" text, "avatar" text, "extra" jsonb DEFAULT '{}'::jsonb NOT NULL,
  "updated_at" bigint NOT NULL,
  CONSTRAINT "contacts_user_id_kind_openid_pk" PRIMARY KEY("user_id","kind","openid")
);
CREATE TABLE IF NOT EXISTS "conversations" (
  "user_id" text NOT NULL, "id" text NOT NULL, "scope" text NOT NULL,
  "peer_id" text NOT NULL, "title" text NOT NULL, "avatar" text, "remark" text,
  "last_message_at" bigint DEFAULT 0 NOT NULL, "last_preview" text DEFAULT '' NOT NULL,
  "unread" integer DEFAULT 0 NOT NULL,
  CONSTRAINT "conversations_user_id_id_pk" PRIMARY KEY("user_id","id")
);
CREATE TABLE IF NOT EXISTS "friend_events" (
  "id" text PRIMARY KEY NOT NULL, "user_id" text NOT NULL, "openid" text NOT NULL,
  "scene" text, "short_code" text, "event_time" bigint NOT NULL, "created_at" bigint NOT NULL
);
CREATE TABLE IF NOT EXISTS "group_robot_events" (
  "id" text PRIMARY KEY NOT NULL, "user_id" text NOT NULL, "event_type" text NOT NULL,
  "group_openid" text NOT NULL, "op_member_openid" text,
  "event_time" bigint NOT NULL, "created_at" bigint NOT NULL
);
CREATE TABLE IF NOT EXISTS "join_requests" (
  "id" text PRIMARY KEY NOT NULL, "user_id" text NOT NULL, "join_request_id" text,
  "group_openid" text NOT NULL, "member_openid" text NOT NULL, "username" text,
  "apply_at" text, "apply_source" text, "invited_by" text, "verify_info" jsonb,
  "risk_tips" text, "status" text DEFAULT 'pending' NOT NULL,
  "created_at" bigint NOT NULL, "processed_at" bigint
);
CREATE TABLE IF NOT EXISTS "messages" (
  "seq" bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  "id" text NOT NULL, "user_id" text NOT NULL, "qq_message_id" text, "reference_idx" text,
  "conversation_id" text NOT NULL, "scope" text NOT NULL, "peer_id" text NOT NULL,
  "direction" text NOT NULL, "sender_id" text, "sender_name" text,
  "msg_type" text NOT NULL, "text" text, "attachments" jsonb DEFAULT '[]'::jsonb NOT NULL,
  "status" text DEFAULT 'sent' NOT NULL, "error" text, "reply" jsonb, "created_at" bigint NOT NULL,
  CONSTRAINT "messages_id_unique" UNIQUE("id")
);
CREATE TABLE IF NOT EXISTS "sessions" (
  "token" text PRIMARY KEY NOT NULL, "user_id" text NOT NULL, "user_agent" text,
  "created_at" bigint NOT NULL, "expires_at" bigint NOT NULL
);
CREATE TABLE IF NOT EXISTS "settings" (
  "user_id" text NOT NULL, "key" text NOT NULL, "value" text NOT NULL,
  CONSTRAINT "settings_user_id_key_pk" PRIMARY KEY("user_id","key")
);
CREATE TABLE IF NOT EXISTS "users" (
  "id" text PRIMARY KEY NOT NULL, "username" text NOT NULL,
  "password_hash" text NOT NULL, "created_at" bigint NOT NULL,
  CONSTRAINT "users_username_unique" UNIQUE("username")
);
CREATE INDEX IF NOT EXISTS "conv_user_time_idx" ON "conversations" ("user_id","last_message_at");
CREATE UNIQUE INDEX IF NOT EXISTS "friend_ev_idx" ON "friend_events" ("user_id","openid");
CREATE INDEX IF NOT EXISTS "group_robot_ev_idx" ON "group_robot_events" ("user_id","created_at");
CREATE UNIQUE INDEX IF NOT EXISTS "join_req_idx" ON "join_requests" ("user_id","join_request_id");
CREATE INDEX IF NOT EXISTS "join_req_user_idx" ON "join_requests" ("user_id","created_at");
CREATE INDEX IF NOT EXISTS "msg_conv_idx" ON "messages" ("user_id","conversation_id","seq");
CREATE UNIQUE INDEX IF NOT EXISTS "msg_qq_idx" ON "messages" ("user_id","qq_message_id");
`;

type GlobalWithSchema = typeof globalThis & { __qqrtSchemaReady?: Promise<void> };

export function ensureSchema(): Promise<void> {
  const g = globalThis as GlobalWithSchema;
  if (!g.__qqrtSchemaReady) {
    g.__qqrtSchemaReady = (async () => {
      let ok = 0;
      for (const chunk of DDL.split(";")) {
        const stmt = chunk.trim();
        if (!stmt) continue;
        try {
          await client.exec(stmt + ";");
          ok += 1;
        } catch (e) {
          // 已存在 / 版本差异：记录但不阻断
          console.error(`[qqrt] ensureSchema 跳过：${stmt.slice(0, 48)} — ${e instanceof Error ? e.message : String(e)}`);
        }
      }
      // 一条都没成功说明 PGlite 实例不可用，清缓存让下次调用重试，并明确抛错
      if (ok === 0) {
        g.__qqrtSchemaReady = undefined;
        throw new Error("ensureSchema: 所有建表语句都失败（PGlite 数据目录可能损坏）");
      }
      console.log(`[qqrt] schema ready (${ok} 条语句)`);
    })();
  }
  return g.__qqrtSchemaReady;
}
